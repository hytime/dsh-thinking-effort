#!/usr/bin/env node
/**
 * Remove the previous build's JavaScript before compiling again.
 *
 * `tsdown` runs with `clean: false` on both of its configs because they share
 * one `outDir`: the second config would delete the first one's output. That
 * makes `lib/` accumulate instead — a chunk from an earlier source layout
 * survives every rebuild, and `files: ["lib/*.js"]` then publishes it. This was
 * not theoretical: a stale `src-*.js` sat beside the current one and would have
 * shipped in the tarball.
 *
 * Only the JS and the declarations are removed. `lib/types` is `tsc`'s output
 * and is regenerated by the next step, so leaving it would let a deleted source
 * file keep its `.d.ts` and publish a declaration for code that no longer
 * exists.
 *
 * @module scripts/clean-build
 */
import { readdirSync, rmSync, statSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const LIB = join(ROOT, 'lib')

/**
 * Remove one path, reporting what went.
 * @param {string} target absolute path.
 * @returns {number} how many entries were removed.
 */
function removeTree(target) {
  let entries = 0
  const walk = (path) => {
    entries += 1
    for (const name of readdirSync(path)) {
      const child = join(path, name)
      if (statSync(child).isDirectory()) walk(child)
    }
  }
  walk(target)
  rmSync(target, { recursive: true, force: true })
  return entries
}

/** Whether anything exists at a path. */
function exists(path) {
  try {
    statSync(path)
    return true
  } catch {
    return false
  }
}

let removed = 0
if (exists(LIB)) removed += removeTree(LIB)
if (removed === 0) {
  console.log('clean-build: nothing to remove')
} else {
  console.log(`clean-build: removed ${removed} entr${removed === 1 ? 'y' : 'ies'} from lib/`)
}
